#!/usr/bin/env python3
"""Authors the run's hotspots (workstream C of docs/VISUAL_RHYTHM_ADVENTURE_PLAN.md): content/run/hotspots/<world>.json for the seven run worlds, the named cinematics thattools/run/make_scenes.py copies into content/run/run.json ("cinematics"), and docs/VISUAL_COVERAGE.md (the matrix: world, scene, hotspot, S outcome, F outcome).

    python3 tools/run/make_hotspots.py          # writes the hotspot files and the coverage doc (make_scenes.py writes the cinematics, the things and the waypoints)

The contract is section 2 of the plan: one hotspot is {id, world, scene, map, anchor, kind, radius_m, min_px, available, look, challenge, on_success, on_failure, cinematic?, default,
repeatable}. A world file is {"world": id, "hotspots": [...]}. The exits of a scene are generated from its `next` and the doorway of each route in `place.rail.exits` (the default is the
first route, the lit "ajar" door); the interactions are authored below, each with a success and a different failure. Outcomes: {route?, flags_set?, cinematic?, energy?, music?}.
A `route` is a scene id (a route of that scene) or a Bassment passage id ("1"). Cinematics are rail actions: {"move": "walk" | "place", "to": waypoint, "bars", "role", "style",
"look_at"?: waypoint, actor or thing}; `walk` stays in the room the rail is in (player_walk), `place` is a journey move (player_move). Flags are world-state ids set by outcomes.

WHERE TO ADD AN OBJECT. The tables are split by world, one module each in tools/run/hotspot_tables/ (warehouse, mothership, underworld, hospital, ward, hospital_late, ward_late).
To add or change an object of a world, edit only that world's module; the helpers (add, exits, ch, ob, ft, sc, cin, out, avail, walk, place, T, W, A, P, finished) and the shared
state (HOTSPOTS, ROWS, CINEMATICS) are in tools/run/hotspots_common.py. This file imports the world modules in a fixed order (below), which sets the order of the worlds in the output
and of the rows of docs/VISUAL_COVERAGE.md, then writes the files. The Bassment's rows of the coverage doc come from hotspot_tables/bassment_section.py.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from hotspots_common import ROOT, CINEMATICS, ROWS, HOTSPOTS  # noqa: E402,F401  (shared state the tables fill; make_scenes.py reads CINEMATICS from here)

# The order of these imports is the order of the output: each module's calls append to HOTSPOTS / ROWS as it is imported.
from hotspot_tables import warehouse, mothership, underworld, hospital, ward, hospital_late, ward_late  # noqa: E402,F401
from hotspot_tables.bassment_section import bassment_section  # noqa: E402

OUT = ROOT / "content/run/hotspots"
DOC = ROOT / "docs/VISUAL_COVERAGE.md"


def apply_acting() -> None:
    """Stage 1d: the acting blocks of the people hotspots and the cast lines of the named cinematics (tools/run/acting_data.py). Idempotent; every character hotspot must have its acting."""
    import acting_data
    by_id = {h["id"]: h for lst in HOTSPOTS.values() for h in lst}
    for hid, block in acting_data.ACTING.items():
        if hid not in by_id:
            raise SystemExit("acting_data.ACTING names a hotspot that does not exist: " + hid)
        by_id[hid]["acting"] = json.loads(json.dumps(block))
    missing = [hid for hid, h in by_id.items() if h["kind"] == "character" and hid not in acting_data.ACTING and hid not in acting_data.NO_ACTOR]
    if missing:
        raise SystemExit("character hotspots without acting: " + ", ".join(missing))
    for name, lines in acting_data.CINE_CAST.items():
        if name not in CINEMATICS:
            raise SystemExit("acting_data.CINE_CAST names a cinematic that does not exist: " + name)
        CINEMATICS[name]["cast"] = json.loads(json.dumps(lines))


def write() -> None:
    apply_acting()
    OUT.mkdir(parents=True, exist_ok=True)
    for world, lst in HOTSPOTS.items():
        (OUT / f"{world}.json").write_text(json.dumps({"world": world, "hotspots": lst}, indent=1, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n")
    lines = ["# Visual coverage matrix (workstream C)", "",
             "Generated by `tools/run/make_hotspots.py` from the same tables that write `content/run/hotspots/<world>.json`; `python3 tools/run/check_hotspots.py` enforces the rules and the reachability.",
             "S = the outcome when the player's last block passes, F = when it fails. Status `verified` = authored and checked (`check_hotspots.py`), wired in the run scene (`RunPlay`, `HotspotView`), resolved both ways by `tests/test_hotspots_engine.gd` and reached by the walks (`tools/run/walk_run.sh`, every tap policy).", "",
             "| World | Scene | Hotspot | Kind | S outcome | F outcome | Available when | Status |", "| --- | --- | --- | --- | --- | --- | --- | --- |"]
    for r in ROWS:
        gate = ", ".join(r["gate"]) or "always"
        dflt = " (default)" if r["default"] else ""
        lines.append(f"| {r['world']} | {r['scene']} | {r['hotspot'].split('.', 1)[1] if r['hotspot'].startswith(r['scene']) else r['hotspot']}{dflt} | {r['kind']} | {r['s']} | {r['f']} | {gate} | verified |")
    lines += bassment_section()
    DOC.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print("%d hotspots in %d worlds, %d cinematics" % (sum(len(v) for v in HOTSPOTS.values()), len(HOTSPOTS), len(CINEMATICS)))
    import apply_staging  # the choice layer's hand-authored staging blocks (docs/CHOICE_CLARITY.md) go back in
    apply_staging.main([])


if __name__ == "__main__":
    write()
