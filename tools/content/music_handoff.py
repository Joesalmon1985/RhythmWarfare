"""Writes docs/MUSIC_HANDOFF.md: for every level of the route map, what it plays now and exactly which Beat Shaper exports replace it.

    python tools/content/music_handoff.py

The sheet is generated from content/run/run.json, content/story/music.json and songs/packs/*/pack.json, so it cannot disagree with the game.
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from common import ROOT, read_json  # noqa: E402

OUT = ROOT / "docs" / "MUSIC_HANDOFF.md"


def main() -> None:
    run = read_json(ROOT / "content/run/run.json")
    music = {n["id"]: n for n in read_json(ROOT / "content/story/music.json")["nodes"]}
    packs = {}
    for pj in sorted((ROOT / "songs/packs").glob("*/pack.json")):
        p = read_json(pj)
        packs[p["id"]] = p
    nodes = run["nodes"]
    by_depth: dict[int, list] = {}
    for n in nodes:
        by_depth.setdefault(min(int(n["depth"]), 4), []).append(n)
    L = ["# Music handoff sheet", "",
         "Generated by `python tools/content/music_handoff.py` from the route map and the packs; regenerate after changing either. "
         "What every level plays today, and exactly what to export to replace it.", "",
         "## What the game needs from a set", "",
         "- One **set** per level: `Beat Shaper - <project>-Drums`, `-Bass` and `-Synth`, each as **.wav and .mid** (six files), the format you already export. "
         "Variants of the same project keep the ` (1)`, ` (2)` suffix on all three of their files.",
         "- **Length:** 16 quarter notes of music. The importer works out whether the render is at 87 BPM (a quarter is two game beats, the Lv1 Warehouse profile) "
         "or at 174 BPM (a quarter is one game beat, the Lv2 Alien Spaceship profile) by measuring the drum recording against the MIDI; it refuses any other tempo "
         "and says so. 87 BPM gives a 32-game-beat phrase (11.03 s), 174 BPM a 16-game-beat phrase (5.52 s); both tile the 64-beat phase.",
         "- **Release tails** are welcome (up to one phrase): they are folded onto the start of the loop. Stems may have different lengths.",
         "- **Drum MIDI:** kick = note 36, snare = note 40 (38 also works). Hats and anything else stay in the audio but are not cues. A set that uses other "
         "notes can be imported with `--kick`/`--snare`.",
         "- **Bass MIDI:** every note becomes a hold on a pad chosen by pitch (lowest note on pad 1). A long line is thinned for the early levels.",
         "- **Synth** is backing: it comes in quietly with the bass.",
         "- **Where to put them:** anywhere (a folder such as `NewMusic/`, or a ZIP). Nothing in the folder is modified.",
         "- **Import and assign (one command per level):** `python tools/content/beatshaper.py apply NewMusic --node <node id> --set \"<project>\" --id <pack id>`. "
         "Add `--audio-only` for a sibling that is an alternate render of the same MIDI. Then `python tools/content/beatshaper.py validate`.",
         "", "## Per level", ""]
    for depth in sorted(by_depth):
        grp = by_depth[depth]
        chart_owner = grp[0]
        L.append(f"### Depth {depth} ({'the last depth: levels here loop onward' if depth == 4 else 'difficulty tier %d' % depth})")
        L.append("")
        L.append("Siblings at one depth play **one chart**, so they share one MIDI. You need **1 set** for the chart"
                 + (f" plus **{len(grp) - 1} alternate render{'s' if len(grp) > 2 else ''}** (same MIDI, different sound) if you want the siblings to sound different." if len(grp) > 1 else "."))
        L.append("")
        L.append("| Node id | Level | World | Plays now | Temporary | Replace with (set / project name) | Role |")
        L.append("| --- | --- | --- | --- | --- | --- | --- |")
        for n in grp:
            m = music[n["id"]]
            ap = packs.get(m["audio"], {})
            cp = packs.get(m["chart"], {})
            proj = ap.get("source", {}).get("project", m["audio"])
            var = ap.get("source", {}).get("variant", 0)
            now = f"{proj}{' (%d)' % var if var else ''}" + (f", treatment `{m['treatment']}`" if m["treatment"] != "none" else "")
            if n is chart_owner:
                role = "chart + sound"
                repl = f"`Lv{n['depth']} {n['title']}`"
            else:
                role = "alternate render (same MIDI as the chart set)"
                repl = f"`Lv{n['depth']} {n['title']}` (export from the same MIDI as `Lv{chart_owner['depth']} {chart_owner['title']}`)"
            L.append(f"| `{n['id']}` | {n['title']} | {n['world']} | {now} | {'yes' if m['temporary'] else 'no'} | {repl} | {role} |")
        L.append("")
        L.append("Files for each project name above, six per set: " + ", ".join(f"`Beat Shaper - Lv{n['depth']} {n['title']}-{p}.{e}`" for n in grp[:1] for p in ("Drums", "Bass", "Synth") for e in ("wav", "mid")) + ".")
        L.append("")
        cmds = []
        for n in grp:
            flag = "" if n is chart_owner else " --audio-only"
            slug = ("lv%d_%s" % (n["depth"], n["id"]))
            cmds.append(f"python tools/content/beatshaper.py apply NewMusic --node {n['id']} --set \"Lv{n['depth']} {n['title']}\" --id {slug}{flag}")
        L.append("```bash")
        L.extend(cmds)
        L.append("```")
        L.append("")
    L += ["## How many sets to replace everything", "",
          f"- Chart sets: **{len(by_depth)}** (one per depth: {', '.join('Lv%d' % d for d in sorted(by_depth))}).",
          f"- Alternate renders (optional, for the sibling sound): **{sum(len(g) - 1 for g in by_depth.values())}**.",
          f"- That is {len(by_depth)} to {len(by_depth) + sum(len(g) - 1 for g in by_depth.values())} sets, "
          f"{6 * len(by_depth)} to {6 * (len(by_depth) + sum(len(g) - 1 for g in by_depth.values()))} files.", "",
          "## What is in the repository now", "",
          "| Pack id | Source | Profile | Phrase | Used by |", "| --- | --- | --- | --- | --- |"]
    for pid, p in packs.items():
        used = ", ".join(f"`{i}`" for i, m in music.items() if pid in (m["audio"], m["chart"]))
        src = p["source"]
        L.append(f"| `{pid}` | {src['project']}{' (%d)' % src['variant'] if src['variant'] else ''} | {p['profile']} | {p['phrase_beats']} beats | {used or 'unused'} |")
    L += ["", "Also in `NewMusic/` but not yet usable: Lv1 Warehouse (2) and Lv2 Alien Spaceship (3) (their bass notes do not line up with their bass MIDI at the "
          "measured tempo), Lv2 Alien Spaceship (1) (no kick or snare notes in the drum MIDI: it uses 39, 42, 43, 46; re-import with `--kick`/`--snare` once you say which "
          "notes mean what), and the Default Project set (an unedited template of the Warehouse groove).", ""]
    OUT.write_text("\n".join(L) + "\n", encoding="utf-8", newline="\n")
    print("wrote", OUT.relative_to(ROOT).as_posix())


if __name__ == "__main__":
    main()
