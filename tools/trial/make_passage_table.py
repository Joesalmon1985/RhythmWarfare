"""Writes docs/TRIAL_PASSAGES.md: all 400 passages with their zone, status, kind, tier, links (the default marked) and a short text.

    python tools/trial/make_passage_table.py
"""
from __future__ import annotations

import collections
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def main() -> None:
    g = json.loads((ROOT / "content/trial/book_graph.json").read_text(encoding="utf-8"))["passages"]
    t = json.loads((ROOT / "content/trial/book_text.json").read_text(encoding="utf-8"))["passages"]
    hand = json.loads((ROOT / "content/trial/passages.json").read_text(encoding="utf-8"))["passages"]
    st = collections.Counter(v["status"] for v in g.values())
    how = collections.Counter(v["how"] for v in t.values())
    L = ["# All 400 passages", "",
         "Generated by `python tools/trial/make_passage_table.py` from `content/trial/book_graph.json`, `book_text.json` and the hand-authored `passages.json`. See `docs/TRIAL_FULL_BOOK.md` for what each status means.", "",
         "* Status: " + ", ".join(f"**{k}** {v}" for k, v in sorted(st.items())),
         "* Text: " + ", ".join(f"{k}: {v}" for k, v in sorted(how.items())),
         "* `*` marks the default link (taken when nobody chooses within four bars). `side` = a passage hung on only so that it can be reached. Hand-authored passages (bold) are 1, 66, 119 and 270.", "",
         "| # | Zone | Status | Kind | Tier | Links (src) | Text |", "| --- | --- | --- | --- | --- | --- | --- |"]
    for i in range(1, 401):
        v = g[str(i)]
        links = []
        for k, l in enumerate(v["links"]):
            mark = "*" if k == v["default"] else ""
            links.append(f"{l['to']}{mark} ({l['src']}{', side' if l.get('side') else ''})")
        extra = ""
        if v.get("enemy"):
            extra += f" fight: {v['enemy']['name']}"
        if v.get("luck"):
            extra += f" luck: {v['luck']['pass']}/{v['luck']['fail']}"
        name = f"**{i}**" if str(i) in hand else str(i)
        L.append(f"| {name} | {v['zone'].replace('dd_', '')} | {v['status']} | {v['kind']}{extra} | {v['tier']} | {', '.join(links) or '-'} | {t[str(i)]['text'].replace('|', '/')[:110]} |")
    (ROOT / "docs" / "TRIAL_PASSAGES.md").write_text("\n".join(L) + "\n", encoding="utf-8", newline="\n")
    print("wrote docs/TRIAL_PASSAGES.md")


if __name__ == "__main__":
    main()
